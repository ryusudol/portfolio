export type Embedding = { x: Float32Array; y: Float32Array; pred: Uint8Array };

const decoded: Partial<Record<keyof typeof RAW, Embedding>> = {};

/** A model's embedding, x and y in [0, 1] (y grows downward). */
export function embedding(model: keyof typeof RAW): Embedding {
  const hit = decoded[model];
  if (hit) return hit;
  const raw = RAW[model];
  const bytes = atob(raw.xy);
  const n = raw.pred.length;
  const e = {
    x: new Float32Array(n),
    y: new Float32Array(n),
    pred: new Uint8Array(n),
  };
  for (let i = 0; i < n; i++) {
    e.x[i] = bytes.charCodeAt(2 * i) / 255;
    e.y[i] = bytes.charCodeAt(2 * i + 1) / 255;
    e.pred[i] = raw.pred.charCodeAt(i) - 48;
  }
  decoded[model] = e;
  return e;
}

