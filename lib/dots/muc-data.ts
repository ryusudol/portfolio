const confidences: Partial<Record<keyof typeof CONFIDENCE_RAW, Uint8Array>> =
  {};

/** Model `model`'s confidence in each class for airplane image `j`. */
export function confidence(model: keyof typeof CONFIDENCE_RAW, j: number) {
  let bytes = confidences[model];
  if (!bytes) {
    const raw = atob(CONFIDENCE_RAW[model]);
    bytes = new Uint8Array(raw.length);
    for (let k = 0; k < raw.length; k++) bytes[k] = raw.charCodeAt(k);
    confidences[model] = bytes;
  }
  return Array.from(bytes.subarray(j * 10, j * 10 + 10), (b) => b / 255);
}
